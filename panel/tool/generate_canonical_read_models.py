"""Generate the finite Dart read schema from the Kotlin canonical model manifest.

Generate the Kotlin manifest from services with:
    ./gradlew :typewriter-api:kspKotlin
Then run from the repository root:
    python3 panel/tool/generate_canonical_read_models.py
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
manifest = root / 'services/sdk/typewriter-api/build/generated/ksp/main/resources/canonical-read-models.json'
target = root / 'panel/lib/shared/editors/application/canonical_read_models.generated.dart'
data = json.loads(manifest.read_text())
target.write_text('// Generated by panel/tool/generate_canonical_read_models.py.\n'
                  'part of "portable_expression.dart";\n\n'
                  '// ignore: unnecessary_raw_strings\n'
                  'const _canonicalReadManifest = r\'\'\'' + json.dumps(data, separators=(',', ':')) + '\'\'\';\n')
