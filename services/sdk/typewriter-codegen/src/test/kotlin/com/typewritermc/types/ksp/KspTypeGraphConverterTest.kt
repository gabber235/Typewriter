val KspTypeGraphConverterTest by testSuite {
    test("scalar conversion produces a complete use") {
        val result = KspTypeGraphConverter().convert(classType("kotlin.String")) as KspTypeConversionResult.Success

        result.root shouldBe ScalarKind.TEXT.use
        result.definitions shouldBe emptyList()
    }

    test("synthetic nullable parent arguments retain explicit nullability only") {
        fun verifyArgument(markedNullable: Boolean) {
            val childParameter = mockk<KSTypeParameter>()
            every { childParameter.name } returns name("T")
            every { childParameter.bounds } returns emptySequence()
            val parentParameter = mockk<KSTypeParameter>()
            every { parentParameter.name } returns name("P")
            every { parentParameter.bounds } returns emptySequence()
            val parent = classDeclaration("example.Parent", listOf(parentParameter))
            val child = classDeclaration("example.Child", listOf(childParameter))
            val parameterType = type(childParameter, Nullability.NULLABLE, markedNullable = markedNullable)
            every { child.superTypes } returns
                sequenceOf(
                    mockk {
                        every { resolve() } returns type(parent, arguments = listOf(argument(parameterType)))
                    },
                )

            val result = KspTypeGraphConverter().convertDeclaration(child) as KspTypeConversionResult.Success
            val childDefinition = result.definitions.single { it.id == (result.root as TypeUse.NamedWrapper).value.definition }
            val parameter = ParameterKey(owner = childDefinition.id, index = 0).template
            childDefinition.parents
                .single()
                .arguments
                .single() shouldBe
                if (markedNullable) parameter.nullable() else parameter
        }

        verifyArgument(markedNullable = true)
        verifyArgument(markedNullable = false)
    }

    test("resource reference requires a generated endpoint") {
        val endpoint = classDeclaration("example.SourceEndpoint")
        val reference =
            classType(
                "com.typewritermc.types.Ref",
                listOf(argument(type(endpoint)), argument(classType("kotlin.String"))),
            )

        val result = KspTypeGraphConverter(linkPolicy = KspLinkPolicy { null }).convert(reference)

        (result as KspTypeConversionResult.Failure).diagnostics.single().message shouldBe
            "The resource reference endpoint is not generated by a reference contract."
    }

    test("generated endpoint produces a link representation") {
        val endpoint = classDeclaration("example.SourceEndpoint")
        val reference =
            classType(
                "com.typewritermc.types.Ref",
                listOf(argument(type(endpoint)), argument(classType("kotlin.String"))),
            )
        val endpointId = EndpointId(value = "example.relation:source")

        val result =
            KspTypeGraphConverter(linkPolicy = KspLinkPolicy { endpointId }).convert(reference) as
                KspTypeConversionResult.Success

        val definition = result.definitions.single()
        result.root shouldBe definition.id.use(listOf(ScalarKind.TEXT.use))
        result.definitions.single().representation shouldBe
            RepresentationTemplate.createLink(
                endpoint = endpointId,
                target =
                    definition.parameters
                        .single()
                        .key.template,
            )
    }

    test("one generated endpoint retains each concrete target as an application argument") {
        val endpoint = classDeclaration("example.SourceEndpoint")
        val endpointId = EndpointId(value = "example.relation:source")
        val converter = KspTypeGraphConverter(linkPolicy = KspLinkPolicy { endpointId })
        val text =
            converter.convert(
                classType(
                    "com.typewritermc.types.Ref",
                    listOf(argument(type(endpoint)), argument(classType("kotlin.String"))),
                ),
            ) as KspTypeConversionResult.Success
        val integer =
            converter.convert(
                classType(
                    "com.typewritermc.types.Ref",
                    listOf(argument(type(endpoint)), argument(classType("kotlin.Int"))),
                ),
            ) as KspTypeConversionResult.Success

        text.definitions.single().id shouldBe integer.definitions.single().id
        text.root shouldBe
            text.definitions
                .single()
                .id
                .use(listOf(ScalarKind.TEXT.use))
        integer.root shouldBe
            integer.definitions.single().id.use(
                listOf(
                    integerScalar(IntegerWidth.SIGNED_THIRTY_TWO).use,
                ),
            )
    }
}

private fun classType(
    qualifiedName: String,
    arguments: List<KSTypeArgument> = emptyList(),
): KSType = type(classDeclaration(qualifiedName), arguments = arguments)

private fun type(
    declaration: KSDeclaration,
    nullability: Nullability = Nullability.NOT_NULL,
    arguments: List<KSTypeArgument> = emptyList(),
    markedNullable: Boolean = nullability == Nullability.NULLABLE,
): KSType =
    mockk {
        every { this@mockk.declaration } returns declaration
        every { this@mockk.nullability } returns nullability
        every { this@mockk.isMarkedNullable } returns markedNullable
        every { this@mockk.arguments } returns arguments
    }

private fun classDeclaration(
    qualifiedName: String,
    parameters: List<KSTypeParameter> = emptyList(),
): KSClassDeclaration {
    val declaration = mockk<KSClassDeclaration>()
    every { declaration.qualifiedName } returns name(qualifiedName)
    every { declaration.packageName } returns name(qualifiedName.substringBeforeLast('.', "example"))
    every { declaration.simpleName } returns name(qualifiedName.substringAfterLast('.'))
    every { declaration.typeParameters } returns parameters
    every { declaration.primaryConstructor } returns null
    every { declaration.superTypes } returns emptySequence()
    every { declaration.declarations } returns emptySequence()
    every { declaration.annotations } returns emptySequence()
    every { declaration.modifiers } returns emptySet()
    every { declaration.classKind } returns ClassKind.CLASS
    return declaration
}

private fun argument(type: KSType): KSTypeArgument =
    mockk {
        every { this@mockk.type } returns
            mockk {
                every { resolve() } returns type
                every { element } returns null
            }
    }

private fun name(value: String): KSName = mockk { every { asString() } returns value }
