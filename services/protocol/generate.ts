import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

import { parseManifest } from "./transport-generator/src/routes/manifest.ts";
import {
  deploymentSubscriptions,
  validateComponentSubscriptions,
} from "./transport-generator/src/routes/subscriptions.ts";

const transportManifest = "services/protocol/transport-routes.yaml";

/** Backend components whose NATS core subscriptions the transport manifest owns. */
const subscribedComponents = [
  {
    component: "auth-typewriter-permissions",
    deployment: "backend/access/auth-typewriter-permissions/deploy/base/workloaddeployment.yaml",
  },
];

const dartOutputs = [
  "panel/lib/infrastructure/protocols/skir/skirout",
  "panel/lib/infrastructure/messaging/generated/skirout",
];

const canonicalReadModels = {
  manifest: "services/sdk/typewriter-api/build/generated/ksp/main/resources/canonical-read-models.json",
  target: "panel/lib/shared/editors/application/canonical_read_models.generated.dart",
};

function run(command: string, args: string[], cwd?: string): void {
  const result = spawnSync(command, args, { stdio: "inherit", cwd });
  if (result.error) throw result.error;
  if (result.status !== 0) process.exit(result.status ?? 1);
}

run("bun", ["services/protocol/check-skir-ids.ts", "skir-src"]);
const routes = parseManifest(readFileSync(transportManifest, "utf8"), transportManifest);
for (const { component, deployment } of subscribedComponents) {
  validateComponentSubscriptions(
    routes,
    component,
    deploymentSubscriptions(readFileSync(deployment, "utf8")),
  );
}
run("bunx", ["--bun", "--no-install", "skir", "gen"]);
run("rustfmt", [
  "--edition", "2024",
  "backend/wasmcloud-utils/src/skirout/base.rs",
  "backend/wasmcloud-utils/src/transport_routes/skirout/mod.rs",
]);
run("dart", ["format", ...dartOutputs]);

// The panel reads the canonical Kotlin read models that KSP derives from the typewriter-api declarations.
run("./gradlew", [":typewriter-api:kspKotlin"], "services");
const manifest = JSON.stringify(JSON.parse(readFileSync(canonicalReadModels.manifest, "utf8")));
writeFileSync(
  canonicalReadModels.target,
  "// Generated by services/protocol/generate.ts from the typewriter-api canonical read models.\n" +
    'part of "portable_expression.dart";\n\n' +
    "// ignore: unnecessary_raw_strings\n" +
    `const _canonicalReadManifest = r'''${manifest}''';\n`,
);
