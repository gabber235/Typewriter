const HEADER = "// Generated by skir gen (typewriter operations, Kotlin target) from operations.yaml. Do not edit.";

/** Kotlin keywords that cannot name a kernel method or parameter without backticks. */
const KOTLIN_KEYWORDS = new Set(["as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface", "is", "null", "object", "package", "return", "super", "this", "throw", "true", "try", "typealias", "typeof", "val", "var", "when", "while"]);

/** The Kotlin numeric types the DSL expands numeric and integer type parameters into. */
const UNSIGNED = ["UByte", "UShort", "UInt", "ULong"] as const;
const SIGNED_INTEGERS = ["Byte", "Short", "Int", "Long", "BigInteger"] as const;

interface Skir {
  readonly dataValue: string;
  readonly listItem: string;
  readonly mapRow: string;
  readonly linkValue: string;
  readonly resourceId: string;
  readonly typeUse: string;
  readonly operationId: string;
  readonly failureId: string;
  readonly imports: readonly string[];
  readonly symbols: CodeGenerator.SymbolProvider;
}

/**
 * Emits the Kotlin operation catalog into the typewriter-api source set: declarations, failure ids, the manifest's
 * enums and records, the rule profile kernel interfaces with their dispatch, the expression DSL and the Unicode tables. Skir names come
 * from the Kotlin symbol provider.
 */
export function emitKotlinOperations(
  catalog: ResolvedOperations,
  unicode: UnicodeTables,
  symbols: CodeGenerator.SymbolProvider,
  input: Pick<CodeGenerator.Input<unknown>, "modules">,
): CodeGenerator.OutputFile[] {
  const imported = (module: string, name: string) => importedKotlinSymbol(symbols.record(skirRecord(input, module, name)));
  const records = {
    dataValue: imported("editor/v1/type_catalog.skir", "DataValue"),
    listItem: imported("editor/v1/type_catalog.skir", "ListItem"),
    mapRow: imported("editor/v1/type_catalog.skir", "MapRow"),
    linkValue: imported("editor/v1/type_catalog.skir", "LinkValue"),
    resourceId: imported("editor/v1/type_catalog.skir", "ResourceId"),
    typeUse: imported("editor/v1/type_catalog.skir", "TypeUse"),
    operationId: imported("editor/v1/expression.skir", "OperationId"),
    failureId: imported("editor/v1/expression.skir", "FailureId"),
  };
  const skir: Skir = {
    dataValue: records.dataValue.name,
    listItem: records.listItem.name,
    mapRow: records.mapRow.name,
    linkValue: records.linkValue.name,
    resourceId: records.resourceId.name,
    typeUse: records.typeUse.name,
    operationId: records.operationId.name,
    failureId: records.failureId.name,
    imports: Object.values(records).flatMap((record) => record.imports),
    symbols,
  };
  return [
    file(`${OPERATIONS_DIRECTORY}/PortableOperationCatalog.kt`, OPERATIONS_PACKAGE, catalogFile(catalog, skir)),
    file(`${OPERATIONS_DIRECTORY}/PortableFailures.kt`, OPERATIONS_PACKAGE, failuresFile(catalog, skir)),
    file(`${OPERATIONS_DIRECTORY}/PortableOperationTypes.kt`, OPERATIONS_PACKAGE, typesFile(catalog, skir)),
    file(`${OPERATIONS_DIRECTORY}/RuleKernels.kt`, OPERATIONS_PACKAGE, kernelsFile(catalog, skir)),
    file("com/typewritermc/expression/PortableOperationDsl.kt", DSL_PACKAGE, dslFile(catalog, skir)),
    { path: `${OPERATIONS_DIRECTORY}/PortableUnicodeTables.kt`, code: emitKotlinUnicodeTables(unicode) },
  ];
}

interface Body {
  readonly imports: readonly string[];
  readonly lines: Lines;
  readonly annotations?: readonly string[];
}

function file(path: string, packageName: string, body: Body): CodeGenerator.OutputFile {
  const imports = [...new Set(body.imports)]
    .filter((line) => !line.startsWith(`import ${packageName}.`) || line.slice(`import ${packageName}.`.length).includes("."))
    .sort();
  return {
    path,
    code: renderDeclarations([
      ...(body.annotations ?? []),
      HEADER,
      BLANK,
      `package ${packageName}`,
      BLANK,
      ...imports,
      BLANK,
      ...body.lines,
    ]),
  };
}

function kdoc(text: string): Lines {
  const words = text.replace(/\s+/gu, " ").trim().split(" ");
  const out: string[] = [];
  let line = "";
  for (const word of words) {
    if (line.length > 0 && line.length + word.length + 1 > 110) {
      out.push(line);
      line = word;
    } else {
      line = line.length === 0 ? word : `${line} ${word}`;
    }
  }
  out.push(line);
  return out.length === 1 ? [`/** ${out[0]!.replaceAll("*/", "*&#47;")} */`] : ["/**", ...out.map((part) => ` * ${part}`), " */"];
}

function escapeKeyword(name: string): string {
  return KOTLIN_KEYWORDS.has(name) ? `\`${name}\`` : name;
}

// Catalog

function catalogFile(catalog: ResolvedOperations, skir: Skir): Body {
  const imports = new Set<string>([...skir.imports, "import com.typewritermc.types.declared", "import com.typewritermc.types.use"]);
  const entries = catalog.operations.map((operation): Lines => [
    ...kdoc(operation.doc),
    `val ${constantName(operation.id)}: PortableOperation =`,
    ...indent(
      [
        "PortableOperation(",
        ...indent([
          `id = ${skir.operationId}(value = ${quoted(operation.id)}),`,
          `profile = OperationProfile.${operation.profile.toUpperCase()},`,
          `doc = ${quoted(operation.doc, "escaped")},`,
          `typeParameters = listOf(${operation.typeParameters
            .map((parameter) => `OperationTypeParameter(${quoted(parameter.name)}, TypeBound.${parameter.bound.toUpperCase()}, explicit = ${parameter.explicit})`)
            .join(", ")}),`,
          "parameters =",
          ...indent([
            "listOf(",
            ...indent(
              operation.parameters.map(
                (parameter) =>
                  `OperationParameter(${quoted(parameter.name)}, ${signature(parameter.type, catalog, skir, imports)}, ParameterKind.${parameter.kind.toUpperCase()}, variadic = ${parameter.variadic}${parameter.defaultCase === undefined ? "" : `, defaultCase = ${quoted(upperCamel(parameter.defaultCase))}`}),`,
              ),
            ),
            "),",
          ]),
          `result = ${signature(operation.result, catalog, skir, imports)},`,
          `failures = listOf(${operation.failures.map((failure) => `KernelFailure.${upperCamel(failure)}`).join(", ")}),`,
          `uses = setOf(${operation.uses.map((use) => `OperationCapability.${use.toUpperCase()}`).join(", ")}),`,
          `itemIds = ${operation.itemIds === undefined ? "null" : `ItemIdentities.${operation.itemIds.toUpperCase()}`},`,
        ]),
        ")",
      ],
      1,
    ),
  ]);
  return {
    imports: [...imports],
    lines: [
      "/** Every operation declared in operations.yaml. */",
      "object PortableOperationCatalog {",
      ...indent(
        separated([
          ...entries,
          [
            "/** Every declared operation, in id order. */",
            "val declarations: List<PortableOperation> =",
            ...indent(["listOf(", ...indent(catalog.operations.map((operation) => `${constantName(operation.id)},`)), ")"]),
          ],
          ["private val byId = declarations.associateBy { it.id.value }"],
          [
            "/** The declaration of [id], or null when this build does not know it. */",
            `fun declaration(id: ${skir.operationId}): PortableOperation? = byId[id.value]`,
          ],
        ]),
      ),
      "}",
    ],
  };
}

function signature(type: Signature, catalog: ResolvedOperations, skir: Skir, imports: Set<string>): string {
  const nested = (value: Signature) => signature(value, catalog, skir, imports);
  switch (type.kind) {
    case "scalar":
      return `Signature.Scalar(Signature.ScalarWord.${type.scalar.toUpperCase()})`;
    case "named": {
      const named = namedKind(catalog, type.name);
      if (named.kind === "read_model") {
        const symbol = importedKotlinSymbol(skir.symbols.record(named.location));
        symbol.imports.forEach((line) => imports.add(line));
        return `Signature.ReadModel(${symbol.name}.serializer)`;
      }
      return `Signature.Named(${upperCamel(type.name)}Type)`;
    }
    case "variable":
      return `Signature.Variable(${quoted(type.name)})`;
    case "nullable":
      return `Signature.Nullable(${nested(type.value)})`;
    case "list":
      return `Signature.ListOf(${nested(type.value)})`;
    case "set":
      return `Signature.SetOf(${nested(type.value)})`;
    case "map":
      return `Signature.MapOf(${nested(type.key)}, ${nested(type.value)})`;
    case "entry":
      return `Signature.EntryOf(${nested(type.key)}, ${nested(type.value)})`;
    case "items":
      return `Signature.Items(${nested(type.value)})`;
    case "link":
      return `Signature.Link(${nested(type.value)})`;
    case "partial":
      return `Signature.Partial(${nested(type.value)})`;
    case "located":
      return `Signature.Located(${nested(type.value)})`;
    case "maybe":
      return `Signature.Maybe(${nested(type.value)})`;
    case "each":
      return `Signature.Each(${nested(type.input)}, ${nested(type.output)})`;
    case "apply":
      return `Signature.Apply(${nested(type.input)}, ${nested(type.output)})`;
    case "step":
      return `Signature.Step(${nested(type.accumulator)}, ${nested(type.item)})`;
    case "comparator":
      return `Signature.Comparator(${nested(type.value)})`;
    case "field_of":
      return `Signature.FieldOf(${nested(type.value)} as Signature.Variable)`;
    case "representation":
      return `Signature.Representation(${nested(type.value)} as Signature.Variable)`;
    case "field_type":
      return `Signature.FieldType(${nested(type.record)} as Signature.Variable, ${quoted(type.field)})`;
  }
}

// Failures

function failuresFile(catalog: ResolvedOperations, skir: Skir): Body {
  const group = (name: string, doc: string, failures: readonly ResolvedFailure[]): Lines => [
    ...kdoc(doc),
    `object ${name} {`,
    ...indent(
      separated([
        ...failures.map((failure): Lines => [
          ...kdoc(failure.message),
          `val ${upperCamel(failure.id)}: ${skir.failureId} = ${skir.failureId}(value = ${quoted(failure.id)})`,
        ]),
        [
          "/** Every failure of this group, in declaration order. */",
          `val all: List<${skir.failureId}> = listOf(${failures.map((failure) => upperCamel(failure.id)).join(", ")})`,
        ],
      ]),
    ),
    "}",
  ];
  return {
    imports: skir.imports,
    lines: separated([
      group("KernelFailure", "Failures operation kernels raise.", catalog.failures),
      group("EvaluatorFailure", "Failures of the structural forms and the call rule, on both hosts.", catalog.evaluatorFailures),
      group("CheckFailure", "Codes the expression checker reports.", catalog.checkFailures),
      group("HostFailure", "Failures hosts raise while reading authored values; evaluators never raise them.", catalog.hostFailures),
    ]),
  };
}

// Enums and records

function typesFile(catalog: ResolvedOperations, skir: Skir): Body {
  const imports = new Set<string>([
    ...skir.imports,
    "import com.typewritermc.types.TypewriterType",
    "import com.typewritermc.types.declared",
    "import com.typewritermc.types.namedUse",
    "import com.typewritermc.types.named",
    "import com.typewritermc.types.record",
    "import com.typewritermc.types.field",
    "import com.typewritermc.types.unwrapNamed",
    "import skirout.editor.v1.type_catalog.TypeDefinitionId",
  ]);
  const enums = catalog.enums.map((enumeration): Lines => {
    const name = upperCamel(enumeration.name);
    return [
      ...kdoc(enumeration.doc),
      `@TypewriterType(id = ${quoted(enumeration.typeId)})`,
      `enum class ${name} { ${enumeration.cases.map(upperCamel).join(", ")} }`,
      BLANK,
      `/** The catalog type of [${name}]. */`,
      `val ${name}Type: ${skir.typeUse} = ${skir.typeUse}.NamedWrapper(TypeDefinitionId.declared(${quoted(enumeration.typeId)}).namedUse())`,
      BLANK,
      `fun ${name}.toDataValue(): ${skir.dataValue} = ${skir.dataValue}.named((${name}Type as ${skir.typeUse}.NamedWrapper).value, ${skir.dataValue}.EnumCaseWrapper(name))`,
      BLANK,
      `internal fun ${skir.dataValue}.as${name}(): ${name} {`,
      ...indent([
        `val case = (unwrapNamed() as? ${skir.dataValue}.EnumCaseWrapper)?.value`,
        `return ${name}.entries.firstOrNull { it.name == case } ?: throw OperationFailure(EvaluatorFailure.IllTypedArgument, "Expected a ${name} case.")`,
      ]),
      "}",
    ];
  });
  const records = catalog.records.map((record): Lines => {
    const name = upperCamel(record.name);
    const fields = record.fields.map((field) => ({ ...field, key: lowerCamel(field.name) }));
    return [
      ...kdoc(record.doc),
      `@TypewriterType(id = ${quoted(record.typeId)})`,
      `data class ${name}(`,
      ...indent(fields.map((field) => `val ${field.key}: ${recordFieldType(field.type)},`)),
      ")",
      BLANK,
      `/** The catalog type of [${name}]. */`,
      `val ${name}Type: ${skir.typeUse} = ${skir.typeUse}.NamedWrapper(TypeDefinitionId.declared(${quoted(record.typeId)}).namedUse())`,
      BLANK,
      `fun ${name}.toDataValue(): ${skir.dataValue} =`,
      ...indent([
        `${skir.dataValue}.named(`,
        ...indent([
          `(${name}Type as ${skir.typeUse}.NamedWrapper).value,`,
          `${skir.dataValue}.record(`,
          ...indent(fields.map((field) => `${quoted(field.key)} to ${encode(field.type, field.key, catalog)},`)),
          "),",
        ]),
        ")",
      ]),
      BLANK,
      `internal fun ${skir.dataValue}.as${name}(): ${name} {`,
      ...indent([
        `val record = unwrapNamed() as? ${skir.dataValue}.RecordWrapper ?: throw OperationFailure(EvaluatorFailure.IllTypedArgument, "Expected a ${name}.")`,
        `fun field(name: String): ${skir.dataValue} = record.field(name) ?: throw OperationFailure(EvaluatorFailure.IllTypedArgument, "Expected a ${name}.")`,
        `return ${name}(`,
        ...indent(fields.map((field) => `${field.key} = ${decode(field.type, `field(${quoted(field.key)})`, catalog)},`)),
        ")",
      ]),
      "}",
    ];
  });
  return {
    imports: [...imports],
    lines: separated([...enums, ...records]),
  };
}

function recordFieldType(type: Signature): string {
  switch (type.kind) {
    case "scalar":
      return DSL_SCALARS[type.scalar];
    case "named":
      return upperCamel(type.name);
    case "nullable":
      return `${recordFieldType(type.value)}?`;
    case "list":
      return `List<${recordFieldType(type.value)}>`;
    default:
      throw new Error(`unsupported record field type ${type.kind}`);
  }
}

// Kernel types and conversions

const KERNEL_SCALARS: Record<string, string> = {
  text: "String",
  boolean: "Boolean",
  int32: "Int",
  integer: "java.math.BigInteger",
  float: "Double",
  decimal: "java.math.BigDecimal",
  bytes: "okio.ByteString",
  duration: "kotlin.time.Duration",
  timestamp: "kotlin.time.Instant",
};

function kernelType(type: Signature, operation: ResolvedOperation, catalog: ResolvedOperations, skir: Skir): string {
  const nested = (value: Signature) => kernelType(value, operation, catalog, skir);
  switch (type.kind) {
    case "scalar":
      return type.scalar === "resource_id" ? skir.resourceId : KERNEL_SCALARS[type.scalar]!;
    case "named": {
      const named = namedKind(catalog, type.name);
      return named.kind === "read_model" ? skir.dataValue : upperCamel(type.name);
    }
    case "variable": {
      const bound = boundOf(operation, type.name);
      return bound === "numeric" ? "PortableNumber" : bound === "integer" ? "java.math.BigInteger" : skir.dataValue;
    }
    case "nullable":
      return type.value.kind === "variable" && boundOf(operation, type.value.name) !== "numeric" && boundOf(operation, type.value.name) !== "integer"
        ? skir.dataValue
        : `${nested(type.value)}?`;
    case "list":
    case "set":
    case "items":
      return concreteItem(type.value) ? `List<${nested(type.value)}>` : `List<${skir.listItem}>`;
    case "map":
      return `List<${skir.mapRow}>`;
    case "entry":
    case "field_type":
    case "representation":
      return skir.dataValue;
    case "link":
      return skir.linkValue;
    case "partial":
      return nested(type.value);
    case "located":
      return `Located<${nested(type.value)}>`;
    case "maybe":
      return `PortableMaybe<${nested(type.value)}>`;
    case "each":
      return `List<${nested(type.output)}>`;
    case "step":
      return "PortableStep";
    case "comparator":
      return "PortableComparator";
    case "apply":
      return "PortableApply";
    case "field_of":
      return "String";
  }
}

/** Kotlin that decodes the DataValue expression `value` into the kernel type of `type`. */
function decode(type: Signature, value: string, catalog: ResolvedOperations, operation?: ResolvedOperation): string {
  const nested = (inner: Signature, expression: string) => decode(inner, expression, catalog, operation);
  switch (type.kind) {
    case "scalar":
      return `${value}.as${upperCamel(type.scalar === "int32" ? "int32" : type.scalar)}()`;
    case "named":
      return namedKind(catalog, type.name).kind === "read_model" ? value : `${value}.as${upperCamel(type.name)}()`;
    case "variable": {
      const bound = operation ? boundOf(operation, type.name) : "any";
      return bound === "numeric" ? `${value}.asNumber()` : bound === "integer" ? `${value}.asInteger()` : value;
    }
    case "nullable":
      return type.value.kind === "variable" && kernelVariableIsValue(type.value.name, operation)
        ? value
        : `${value}.asNullable { ${nested(type.value, "it")} }`;
    case "list":
    case "set":
    case "items":
      return concreteItem(type.value) ? `${value}.asItems().map { ${nested(type.value, "it.value")} }` : `${value}.asItems()`;
    case "map":
      return `${value}.asRows()`;
    case "link":
      return `${value}.asLink()`;
    case "field_of":
      return `${value}.asText()`;
    case "entry":
    case "field_type":
    case "representation":
      return value;
    case "partial":
    case "located":
      return nested(type.value, value);
    default:
      throw new Error(`${type.kind} is not decoded from a value`);
  }
}

function kernelVariableIsValue(name: string, operation?: ResolvedOperation): boolean {
  const bound = operation ? boundOf(operation, name) : "any";
  return bound !== "numeric" && bound !== "integer";
}

/** Kotlin that encodes the kernel value `value` of `type` as a DataValue. */
function encode(type: Signature, value: string, catalog: ResolvedOperations, operation?: ResolvedOperation): string {
  const nested = (inner: Signature, expression: string) => encode(inner, expression, catalog, operation);
  switch (type.kind) {
    case "scalar":
      return `${lowerCamel(type.scalar)}Value(${value})`.replace("resource_idValue", "resourceIdValue");
    case "named":
      return namedKind(catalog, type.name).kind === "read_model" ? value : `${value}.toDataValue()`;
    case "variable": {
      const bound = operation ? boundOf(operation, type.name) : "any";
      return bound === "numeric" ? `numberValue(${value})` : bound === "integer" ? `integerValue(${value})` : value;
    }
    case "nullable":
      return type.value.kind === "variable" && kernelVariableIsValue(type.value.name, operation)
        ? value
        : `nullableValue(${value}) { ${nested(type.value, "it")} }`;
    case "list":
      return concreteItem(type.value) ? `positionalList(${value}.map { ${nested(type.value, "it")} })` : `itemsList(${value})`;
    case "set":
      return concreteItem(type.value) ? `itemsSet(positionalItems(${value}.map { ${nested(type.value, "it")} }))` : `itemsSet(${value})`;
    case "map":
      return `rowsMap(${value})`;
    case "link":
      return `linkValue(${value})`;
    case "entry":
    case "field_type":
    case "representation":
      return value;
    default:
      throw new Error(`${type.kind} is not an encodable result`);
  }
}

// Kernels

function kernelName(group: string): string {
  return `${upperCamel(group)}Kernel`;
}

function kernelMethodName(operation: ResolvedOperation): string {
  return escapeKeyword(lowerCamel(operation.name));
}

function kernelParameters(operation: ResolvedOperation, catalog: ResolvedOperations, skir: Skir): string[] {
  const values = operation.parameters.map((parameter) => {
    const type = kernelType(parameter.type, operation, catalog, skir);
    return `${escapeKeyword(lowerCamel(parameter.name))}: ${parameter.variadic ? `List<${type}>` : type}`;
  });
  const types = operation.typeParameters
    .filter((parameter) => parameter.explicit)
    .map((parameter) => `${parameter.name.toLowerCase()}Type: ${skir.typeUse}`);
  const capabilities = operation.uses.flatMap((use) =>
    use === "meter" ? ["meter: PortableMeter"] : use === "types" ? ["types: PortableTypes"] : [],
  );
  return [...values, ...types, ...capabilities];
}

function kernelsFile(catalog: ResolvedOperations, skir: Skir): Body {
  const rule = catalog.operations.filter((operation) => operation.profile === "rule");
  const groups = operationGroups(rule);
  const interfaces = groups.map(([group, operations]): Lines => [
    `/** The rule profile operations of group ${group}; Realm implements every method. */`,
    `interface ${kernelName(group)} {`,
    ...indent(
      separated(
        operations.map((operation): Lines => {
          const result = kernelType(operation.result, operation, catalog, skir);
          const parameters = kernelParameters(operation, catalog, skir);
          return [
            ...kdoc(operation.doc),
            parameters.length <= 2
              ? `fun ${kernelMethodName(operation)}(${parameters.join(", ")}): ${result}`
              : `fun ${kernelMethodName(operation)}(`,
            ...(parameters.length <= 2 ? [] : [...indent(parameters.map((parameter) => `${parameter},`)), `): ${result}`]),
          ];
        }),
      ),
    ),
    "}",
  ]);
  const holder: Lines = [
    "/** Every rule profile kernel group Realm implements. */",
    "class RuleKernels(",
    ...indent(groups.map(([group]) => `val ${escapeKeyword(lowerCamel(group))}: ${kernelName(group)},`)),
    ")",
  ];
  const invoker: Lines = [
    "/** The invoker of the rule profile operation [id], or null when Realm does not implement it. */",
    `internal fun RuleKernels.invoker(id: ${skir.operationId}): OperationInvoker? =`,
    ...indent([
      "when (id.value) {",
      ...indent(rule.flatMap((operation) => invokerCase(operation, catalog, skir))),
      ...indent(["else -> null"]),
      "}",
    ]),
  ];
  return {
    imports: [...skir.imports, "import com.typewritermc.authoring.Availability"],
    lines: separated([...interfaces, holder, invoker]),
  };
}

function invokerCase(operation: ResolvedOperation, catalog: ResolvedOperations, skir: Skir): Lines {
  const argumentsOf = operation.parameters.map((parameter, index) => argument(parameter, index, operation, catalog));
  const typeArguments = operation.typeParameters
    .filter((parameter) => parameter.explicit)
    .map((_, index) => `typeArguments[${index}]`);
  const capabilities = operation.uses.flatMap((use) => (use === "meter" ? ["context.meter"] : use === "types" ? ["context.types"] : []));
  const call = `${escapeKeyword(lowerCamel(operation.group))}.${kernelMethodName(operation)}(${[...argumentsOf, ...typeArguments, ...capabilities].join(", ")})`;
  const body =
    operation.result.kind === "maybe"
      ? `${call}.toAvailability { ${encode(operation.result.value, "it", catalog, operation)} }`
      : `Availability.Available(${encode(operation.result, call, catalog, operation)})`;
  const unused = [
    argumentsOf.length === 0 ? "_" : "arguments",
    typeArguments.length === 0 ? "_" : "typeArguments",
    capabilities.length === 0 ? "_" : "context",
  ];
  return [
    `${quoted(operation.id)} ->`,
    ...indent([
      `OperationInvoker(PortableOperationCatalog.${constantName(operation.id)}) { ${unused.join(", ")} ->`,
      ...indent([body]),
      "}",
    ]),
  ];
}

function argument(parameter: ResolvedParameter, index: number, operation: ResolvedOperation, catalog: ResolvedOperations): string {
  if (parameter.variadic) {
    return `arguments.drop(${index}).map { ${decode(parameter.type, "it.value()", catalog, operation)} }`;
  }
  const at = `arguments[${index}]`;
  switch (parameter.kind) {
    case "value":
    case "partial":
      return decode(parameter.type, `${at}.value()`, catalog, operation);
    case "located":
      return `${at}.located { ${decode(unwrapped(parameter.type), "it", catalog, operation)} }`;
    case "each": {
      const output = (parameter.type as { output: Signature }).output;
      return `${at}.each { ${decode(output, "it", catalog, operation)} }`;
    }
    case "step":
      return `${at}.step()`;
    case "comparator":
      return `${at}.comparator()`;
    case "apply":
      return `${at}.apply()`;
  }
}

// DSL

const DSL_SCALARS: Record<string, string> = {
  text: "String",
  boolean: "Boolean",
  int32: "Int",
  integer: "Long",
  float: "Double",
  decimal: "java.math.BigDecimal",
  bytes: "ByteArray",
  duration: "kotlin.time.Duration",
  timestamp: "kotlin.time.Instant",
  resource_id: "com.typewritermc.types.ResourceId",
};

/** The Kotlin types one DSL variant substitutes for type parameters. */
type Substitution = ReadonlyMap<string, string>;

interface DslVariant {
  readonly suffix: string;
  readonly typeParameters: readonly string[];
  readonly substitution: Substitution;
  /** A numeric variable the variant fixes to an unsigned or integer Kotlin type, for raw literals. */
  readonly numeric?: { readonly variable: string; readonly kotlin: string };
  /** The receiver type when it differs from the parameter's rendering, such as a map receiver of items. */
  readonly receiver?: string;
}

function dslFile(catalog: ResolvedOperations, skir: Skir): Body {
  const imports = new Set<string>([
    "import com.typewritermc.expression.operations.PortableOperationCatalog",
    "import com.typewritermc.types.Ref",
    "import com.typewritermc.types.Resource",
    "import java.math.BigInteger",
  ]);
  const functions = catalog.operations.flatMap((operation) =>
    operation.dsl === "hand" ? [] : dslFunctions(operation, catalog, skir, imports),
  );
  const enumLiterals = catalog.enums.map((enumeration): Lines => {
    const name = upperCamel(enumeration.name);
    imports.add(`import ${OPERATIONS_PACKAGE}.${name}`);
    imports.add(`import ${OPERATIONS_PACKAGE}.toDataValue`);
    return [`fun literal(value: ${name}): Expr<${name}, Handled> = portableLiteral(value.toDataValue())`];
  });
  for (const record of catalog.records) {
    imports.add(`import ${OPERATIONS_PACKAGE}.${upperCamel(record.name)}`);
  }
  return {
    annotations: ['@file:Suppress("unused", "RedundantVisibilityModifier")'],
    imports: [...imports],
    lines: separated([...enumLiterals, ...functions]),
  };
}

function dslFunctions(operation: ResolvedOperation, catalog: ResolvedOperations, skir: Skir, imports: Set<string>): Lines[] {
  const dsl = operation.dsl as Exclude<ResolvedOperation["dsl"], "hand">;
  for (const parameter of operation.parameters) collectDslImports(parameter.type, catalog, skir, imports);
  collectDslImports(operation.result, catalog, skir, imports);
  return dslVariants(operation).flatMap((variant) => {
    const exprForm = dslFunction(operation, dsl, variant, catalog, skir, false);
    const rawForm = hasRawParameters(operation, dsl) ? [dslFunction(operation, dsl, variant, catalog, skir, true)] : [];
    return [exprForm, ...rawForm];
  });
}

function collectDslImports(type: Signature, catalog: ResolvedOperations, skir: Skir, imports: Set<string>): void {
  const visit = (value: Signature): void => {
    switch (value.kind) {
      case "named": {
        const named = namedKind(catalog, value.name);
        if (named.kind === "read_model") {
          importedKotlinSymbol(skir.symbols.record(named.location)).imports.forEach((line) => imports.add(line));
        }
        return;
      }
      case "scalar":
      case "variable":
        return;
      case "map":
      case "entry":
        visit(value.key);
        return visit(value.value);
      case "each":
      case "apply":
        visit(value.input);
        return visit(value.output);
      case "step":
        visit(value.accumulator);
        return visit(value.item);
      case "field_type":
        return visit(value.record);
      default:
        return visit(value.value);
    }
  };
  visit(type);
}

/** The overloads one operation expands into: numeric bounds per Kotlin number type, items per collection kind. */
function dslVariants(operation: ResolvedOperation): DslVariant[] {
  const dsl = operation.dsl as Exclude<ResolvedOperation["dsl"], "hand">;
  const plain = operation.typeParameters.map((parameter) => parameter.name);
  let variants: DslVariant[] = [{ suffix: "", typeParameters: plain, substitution: new Map() }];
  const numeric = operation.typeParameters.find((parameter) => parameter.bound === "numeric");
  const integer = operation.typeParameters.find((parameter) => parameter.bound === "integer");
  if (numeric) {
    const others = plain.filter((name) => name !== numeric.name);
    variants = [
      { suffix: "", typeParameters: [`${numeric.name} : Number`, ...others], substitution: new Map() },
      ...UNSIGNED.map((kotlin) => ({
        suffix: kotlin,
        typeParameters: others,
        substitution: new Map([[numeric.name, kotlin]]),
        numeric: { variable: numeric.name, kotlin },
      })),
    ];
  } else if (integer) {
    const others = plain.filter((name) => name !== integer.name);
    variants = [...SIGNED_INTEGERS, ...UNSIGNED].map((kotlin) => ({
      suffix: kotlin,
      typeParameters: others,
      substitution: new Map([[integer.name, kotlin]]),
      numeric: { variable: integer.name, kotlin },
    }));
  }
  const receiver = dsl.receiver ? operation.parameters[0] : undefined;
  const receiverItems = receiver ? unwrapped(receiver.type) : undefined;
  if (receiverItems?.kind === "items") {
    variants = variants.flatMap((variant) => {
      const item = receiverItems.value;
      if (item.kind === "variable") {
        const others = variant.typeParameters.filter((name) => name !== item.name);
        return [
          variant,
          {
            ...variant,
            suffix: `${variant.suffix}OfMap`,
            typeParameters: [...others, `${item.name}K`, `${item.name}V`],
            substitution: new Map([...variant.substitution, [item.name, `Map.Entry<${item.name}K, ${item.name}V>`]]),
            receiver: `Map<${item.name}K, ${item.name}V>`,
          },
        ];
      }
      if (item.kind === "entry" && item.key.kind === "variable" && item.value.kind === "variable") {
        return [variant, { ...variant, suffix: `${variant.suffix}OfMap`, receiver: `Map<${item.key.name}, ${item.value.name}>` }];
      }
      return [variant];
    });
  }
  const linked = new Set<string>();
  const findLinks = (type: Signature): void => {
    if (type.kind === "link" && type.value.kind === "variable") linked.add(type.value.name);
    if ("value" in type && typeof type.value === "object") findLinks(type.value);
  };
  operation.parameters.forEach((parameter) => findLinks(parameter.type));
  findLinks(operation.result);
  return variants.map((variant) => ({
    ...variant,
    typeParameters: variant.typeParameters.map((name) => (linked.has(name) ? `${name} : Resource` : name)),
  }));
}

function hasRawParameters(operation: ResolvedOperation, dsl: Exclude<ResolvedOperation["dsl"], "hand">): boolean {
  return operation.parameters.some((parameter, index) => !(dsl.receiver && index === 0) && rawKind(parameter, operation) !== undefined);
}

/** How a parameter takes a raw Kotlin value in the literal overload, or undefined when it stays an expression. */
function rawKind(parameter: ResolvedParameter, operation: ResolvedOperation): "scalar" | "numeric" | undefined {
  if (parameter.variadic || parameter.kind !== "value") return undefined;
  const type = parameter.type;
  if (type.kind === "scalar" && type.scalar !== "bytes") return "scalar";
  if (type.kind === "variable") {
    const bound = boundOf(operation, type.name);
    if (bound === "numeric" || bound === "integer") return "numeric";
  }
  return undefined;
}

/** Kotlin type of an expression of `type` in a DSL variant. */
function dslType(type: Signature, variant: DslVariant, catalog: ResolvedOperations, skir: Skir): string {
  const nested = (value: Signature) => dslType(value, variant, catalog, skir);
  switch (type.kind) {
    case "scalar":
      return DSL_SCALARS[type.scalar]!;
    case "named": {
      const named = namedKind(catalog, type.name);
      return named.kind === "read_model" ? importedKotlinSymbol(skir.symbols.record(named.location)).name : upperCamel(type.name);
    }
    case "variable":
      return variant.substitution.get(type.name) ?? type.name;
    case "nullable":
      return `${nested(type.value)}?`;
    case "list":
      return `List<${nested(type.value)}>`;
    case "set":
      return `Set<${nested(type.value)}>`;
    case "items":
      return `Collection<${nested(type.value)}>`;
    case "map":
      return `Map<${nested(type.key)}, ${nested(type.value)}>`;
    case "entry":
      return `Map.Entry<${nested(type.key)}, ${nested(type.value)}>`;
    case "link":
      return `Ref<*, ${nested(type.value)}>`;
    case "partial":
    case "located":
    case "maybe":
      return nested(type.value);
    default:
      throw new Error(`${type.kind} has no DSL expression type`);
  }
}

function isCollectionType(type: Signature): boolean {
  return ["list", "set", "items", "map", "link"].includes(type.kind);
}

/**
 * `Expr<T, M>`, with an out projection for collection types so List<String> fits Collection<String>, and for nullable
 * types so an expression of a non null type fits a parameter that also accepts null.
 */
function exprOf(type: Signature, variant: DslVariant, catalog: ResolvedOperations, skir: Skir, policy: string): string {
  const kotlin = dslType(type, variant, catalog, skir);
  const shape = unwrapped(type);
  return `Expr<${isCollectionType(shape) || shape.kind === "nullable" ? "out " : ""}${kotlin}, ${policy}>`;
}

function lambdaType(parameter: ResolvedParameter, variant: DslVariant, catalog: ResolvedOperations, skir: Skir, items?: Signature): string {
  const local = (type: Signature) => `Expr<${dslType(type, variant, catalog, skir)}, MayBeMissing>`;
  const body = (type: Signature) => `Expr<${dslType(type, variant, catalog, skir)}, out MissingPolicy>`;
  const type = parameter.type;
  switch (type.kind) {
    case "each":
      return `${local(items ?? type.input)}.() -> ${body(type.output)}`;
    case "apply":
      return `(${local(type.input)}) -> ${body(type.output)}`;
    case "step":
      return `(${local(type.accumulator)}, ${local(type.item)}) -> ${body(type.accumulator)}`;
    case "comparator":
      return `(${local(type.value)}, ${local(type.value)}) -> Expr<Int, out MissingPolicy>`;
    default:
      throw new Error(`${type.kind} is not a lambda`);
  }
}

function dslFunction(
  operation: ResolvedOperation,
  dsl: Exclude<ResolvedOperation["dsl"], "hand">,
  variant: DslVariant,
  catalog: ResolvedOperations,
  skir: Skir,
  raw: boolean,
): Lines {
  const lambdas = operation.parameters.some((parameter) => ["each", "step", "comparator", "apply"].includes(parameter.kind));
  const resultPolicy = operation.result.kind === "maybe" || lambdas ? "MayBeMissing" : "M";
  const receiver = dsl.receiver ? operation.parameters[0]! : undefined;
  const itemType = receiver ? itemOf(unwrapped(receiver.type), variant) : undefined;

  const declared: string[] = [];
  const callArguments: string[] = [];
  const typeParameters = [...variant.typeParameters, "M : MissingPolicy"];
  operation.parameters.forEach((parameter, index) => {
    const name = escapeKeyword(lowerCamel(parameter.name));
    if (receiver && index === 0) {
      callArguments.push("this");
      return;
    }
    if (parameter.kind === "each" || parameter.kind === "step" || parameter.kind === "comparator" || parameter.kind === "apply") {
      callArguments.push(
        parameter.kind === "each" ? `lambda1(${name})` : parameter.kind === "apply" ? `lambdaOf(${name})` : `lambda2(${name})`,
      );
      return;
    }
    const type = parameter.type;
    if (type.kind === "named" && namedKind(catalog, type.name).kind === "enum") {
      const enumName = upperCamel(type.name);
      const fallback = parameter.defaultCase === undefined ? "" : ` = ${enumName}.${upperCamel(parameter.defaultCase)}`;
      declared.push(`${name}: ${enumName}${fallback}`);
      callArguments.push(`literal(${name})`);
      return;
    }
    if (parameter.variadic) {
      // Infix and operator functions take exactly one argument; longer chains nest the binary form.
      if (dsl.operator || dsl.infix) return;
      declared.push(`vararg ${name}: ${exprOf(type, variant, catalog, skir, "M")}`);
      callArguments.push(`*${name}`);
      return;
    }
    const rawAs = raw ? rawKind(parameter, operation) : undefined;
    if (rawAs === "scalar") {
      declared.push(`${name}: ${dslType(type, variant, catalog, skir)}`);
      callArguments.push(`literal(${name})`);
      return;
    }
    if (rawAs === "numeric") {
      const kotlin = dslType(type, variant, catalog, skir);
      declared.push(`${name}: ${kotlin}`);
      callArguments.push(UNSIGNED.includes(kotlin as (typeof UNSIGNED)[number]) ? `literal(${name})` : `numericLiteral(${name})`);
      return;
    }
    declared.push(`${name}: ${exprOf(type, variant, catalog, skir, "M")}`);
    callArguments.push(name);
  });
  const lambdaParameters = operation.parameters
    .filter((parameter) => ["each", "step", "comparator", "apply"].includes(parameter.kind))
    .map((parameter) => `${escapeKeyword(lowerCamel(parameter.name))}: ${lambdaType(parameter, variant, catalog, skir, itemType)}`);
  const parameters = [...declared, ...lambdaParameters];

  const result = `Expr<${dslType(operation.result, variant, catalog, skir)}, ${resultPolicy}>`;
  const receiverType = receiver
    ? variant.receiver
      ? `Expr<out ${variant.receiver}, M>`
      : exprOf(receiver.type, variant, catalog, skir, "M")
    : undefined;
  const typeList = `<${typeParameters.join(", ")}>`;
  const jvmName = `${lowerCamel(operation.group)}${upperCamel(operation.name)}${variant.suffix}${raw ? "Raw" : ""}`;
  const body = `call(PortableOperationCatalog.${constantName(operation.id)}, ${callArguments.join(", ")})`;
  const doc = kdoc(operation.doc);
  if (dsl.property) {
    return [...doc, `@get:JvmName(${quoted(jvmName)})`, `val ${typeList} ${receiverType}.${dsl.name}: ${result}`, ...indent([`get() = ${body}`])];
  }
  const modifiers = [dsl.operator ? "operator " : "", dsl.infix ? "infix " : ""].join("");
  const head = `${modifiers}fun ${typeList} ${receiverType ? `${receiverType}.` : ""}${escapeKeyword(dsl.name)}(`;
  return [
    ...doc,
    `@JvmName(${quoted(jvmName)})`,
    parameters.length === 0 ? `${head}): ${result} =` : head,
    ...(parameters.length === 0 ? [] : [...indent(parameters.map((parameter) => `${parameter},`)), `): ${result} =`]),
    ...indent([body]),
  ];
}

/** The item type the each lambdas of a receiver of `type` see. */
function itemOf(type: Signature, variant: DslVariant): Signature | undefined {
  if (type.kind === "items" || type.kind === "list" || type.kind === "set") {
    if (variant.receiver && type.value.kind === "entry") return type.value;
    return type.value;
  }
  if (type.kind === "map") return { kind: "entry", key: type.key, value: type.value };
  return undefined;
}
