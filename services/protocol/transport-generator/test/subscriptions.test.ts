import { describe, expect, test } from "bun:test";
import { parse } from "yaml";

import { subscriptionConfigMaps } from "../src/routes/subscriptions.js";
import { committedManifest } from "./support.js";

/** A WorkloadDeployment whose metadata names a workload `<component>` in the typewriter namespace. */
function deployment(path: string): string {
  const component = path.split("/").at(-4)!;
  return `apiVersion: runtime.wasmcloud.dev/v1alpha1\nkind: WorkloadDeployment\nmetadata:\n  name: ${component}\n  namespace: typewriter\n`;
}

describe("subscription ConfigMaps", () => {
  test("every receiving component gets one ConfigMap in its deploy/base directory", () => {
    const read: string[] = [];
    const files = subscriptionConfigMaps(committedManifest(), (path) => {
      read.push(path);
      return deployment(path);
    });
    expect(files.map((file) => file.path)).toEqual([
      "backend/organization/user-organization/deploy/base/nats-subscriptions.generated.yaml",
      "backend/organization/organization-members/deploy/base/nats-subscriptions.generated.yaml",
      "backend/organization/organization-roles/deploy/base/nats-subscriptions.generated.yaml",
      "backend/service/service-registration/deploy/base/nats-subscriptions.generated.yaml",
      "backend/access/auth-typewriter-permissions/deploy/base/nats-subscriptions.generated.yaml",
    ]);
    expect(read).not.toContain("backend/access/auth-callout/deploy/base/workloaddeployment.yaml");
  });

  test("lists each dispatched subject in the workload's queue group", () => {
    const [, , roles, , permissions] = subscriptionConfigMaps(committedManifest(), deployment);
    expect(roles!.code).toBe(
      [
        "# GENERATED by services/protocol/transport-generator from services/protocol/transport-routes.yaml.",
        "# Do not edit; regenerate with `bun run generate:protocol`.",
        "apiVersion: v1",
        "kind: ConfigMap",
        "metadata:",
        "  name: organization-roles-nats-subscriptions",
        "  namespace: typewriter",
        "data:",
        "  core-subscriptions: >-",
        "    typewriter.from.user.*.organization.*.roles.watch:typewriter.organization-roles",
        "",
      ].join("\n"),
    );
    expect(parse(permissions!.code).data).toEqual({
      "core-subscriptions":
        "auth.permissions.typewriter-panel:typewriter.auth-typewriter-permissions, " +
        "auth.permissions.typewriter-services:typewriter.auth-typewriter-permissions",
    });
  });

  test("rejects a deployment without valid workload metadata", () => {
    expect(() => subscriptionConfigMaps(committedManifest(), () => "metadata: {}\n")).toThrow(
      "backend/organization/user-organization/deploy/base/workloaddeployment.yaml: invalid WorkloadDeployment metadata",
    );
  });
});
